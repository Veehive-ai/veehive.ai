#!/usr/bin/env python3
"""Render the mark with its padding baked in.

    python3 make-padded.py

The plain mark files are cropped tight to the petals, which is right when you
are placing it yourself and applying clear space by hand. These are for the
places that will not do that for you — an app tile, a profile square, a slide
master, anything that takes a square image and crops or centres it as-is.

The padding matches the reference Sathish supplied on 2026-11-10: the petals
occupy 62% of the square's width (and so 66.7% of its height, the mark being
taller than it is wide). That is deliberately tighter than the guide's
clear-space rule of one petal height, because here the margin is inside the
file rather than around it.

Note this is NOT the avatar. Avatars are generated by social/make-social.py at
74%, because a circular crop eats the corners and the mark has to grow to hold
its weight inside the circle.
"""
import os, re, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
CHROME = os.environ.get(
    'CHROME', '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome')

SRC = os.path.join(HERE, 'veehive-mark.svg')
RATIO = 0.62                      # petal width as a share of the square
SIZES = (256, 512, 1024)
WHITE_SIZES = (512, 1024)


def padded_svg():
    """Wrap the master mark in a square viewBox with the margin built in."""
    s = open(SRC, encoding='utf-8').read()
    m = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', s)
    w, h = float(m.group(1)), float(m.group(2))
    side = round(w / RATIO, 2)
    dx, dy = round((side - w) / 2, 2), round((side - h) / 2, 2)
    body = s[s.index('>', s.index('<svg')) + 1:s.rindex('</svg>')]
    return ('<svg width="%g" height="%g" viewBox="0 0 %g %g" fill="none" '
            'xmlns="http://www.w3.org/2000/svg">\n'
            '<g transform="translate(%g %g)">%s</g>\n</svg>\n'
            % (side, side, side, side, dx, dy, body)), side, w, h


def shot(html, path, size, transparent):
    tmp = os.path.join(HERE, '_pad.html')
    open(tmp, 'w', encoding='utf-8').write(html)
    cmd = [CHROME, '--headless', '--disable-gpu', '--hide-scrollbars',
           '--window-size=%d,%d' % (size, size), '--screenshot=' + path,
           '--virtual-time-budget=4000']
    if transparent:
        cmd.append('--default-background-color=00000000')
    cmd.append('file://' + tmp)
    subprocess.run(cmd, capture_output=True)
    os.remove(tmp)
    return os.path.exists(path)


def page(ground, size):
    return ("<!doctype html><meta charset='utf-8'><style>"
            "*{margin:0;padding:0}html,body{width:%dpx;height:%dpx;overflow:hidden%s}"
            "img{width:100%%;height:100%%;display:block}</style>"
            "<img src='veehive-mark-padded.svg' alt=''>"
            % (size, size, (';background:' + ground) if ground else ''))


if __name__ == '__main__':
    svg, side, w, h = padded_svg()
    out = os.path.join(HERE, 'veehive-mark-padded.svg')
    open(out, 'w', encoding='utf-8').write(svg)
    print('  svg     %-34s %gx%g, petals %.1f%% wide / %.1f%% tall'
          % ('veehive-mark-padded.svg', side, side, 100 * w / side, 100 * h / side))

    for s in SIZES:
        f = os.path.join(HERE, 'veehive-mark-padded-%d.png' % s)
        if shot(page(None, s), f, s, True):
            print('  png     %-34s %dx%d  transparent' % (os.path.basename(f), s, s))
    for s in WHITE_SIZES:
        f = os.path.join(HERE, 'veehive-mark-padded-white-%d.png' % s)
        if shot(page('#FFFFFF', s), f, s, False):
            print('  png     %-34s %dx%d  on white' % (os.path.basename(f), s, s))
